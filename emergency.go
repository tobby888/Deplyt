package main

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"strings"
	"sync"

	"golang.org/x/crypto/argon2"
)

const (
	emergencyAccountID  = "emergency"
	emergencyHashPrefix = "$argon2id$v=19$m=19456,t=2,p=1$"
	emergencySaltSize   = 16
	emergencyDigestSize = 32
)

type emergencyPassword struct {
	salt   []byte
	digest []byte
	verify sync.Mutex
}

func parseEmergencyPassword(value string) (*emergencyPassword, error) {
	if value == "" {
		return nil, nil
	}
	encoded, prefixOK := strings.CutPrefix(value, emergencyHashPrefix)
	saltText, digestText, splitOK := strings.Cut(encoded, "$")
	salt, saltErr := base64.RawStdEncoding.Strict().DecodeString(saltText)
	digest, digestErr := base64.RawStdEncoding.Strict().DecodeString(digestText)
	if !prefixOK || !splitOK || saltErr != nil || digestErr != nil ||
		len(salt) != emergencySaltSize || len(digest) != emergencyDigestSize {
		return nil, errors.New("DEPLOY_EMERGENCY_PASSWORD_HASH must contain the hash generated by deplyt generate-emergency-password")
	}
	return &emergencyPassword{salt: salt, digest: digest}, nil
}

func emergencyDigest(password string, salt []byte) []byte {
	return argon2.IDKey([]byte(password), salt, 2, 19*1024, 1, emergencyDigestSize)
}

func generateEmergencyPassword(out io.Writer) error {
	password := randomToken()
	salt := make([]byte, emergencySaltSize)
	rand.Read(salt)
	digest := emergencyDigest(password, salt)
	_, err := fmt.Fprintf(out, "应急密码 %s\nDEPLOY_EMERGENCY_PASSWORD_HASH='%s%s$%s'\n",
		password, emergencyHashPrefix, base64.RawStdEncoding.EncodeToString(salt), base64.RawStdEncoding.EncodeToString(digest))
	return err
}

func (a *consoleAuth) emergencyLogin(logger *slog.Logger) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		password := a.emergency
		if password == nil {
			http.NotFound(w, r)
			return
		}
		if r.Header.Get("Origin") != a.origin {
			http.Error(w, "请求来源无效", http.StatusForbidden)
			return
		}
		var input struct {
			Password string `json:"password"`
		}
		body := http.MaxBytesReader(w, r.Body, 1024)
		if err := json.NewDecoder(body).Decode(&input); err != nil || input.Password == "" {
			http.Error(w, "请输入应急密码", http.StatusBadRequest)
			return
		}
		// Limit concurrent Argon2id work without locking out future requests.
		if !password.verify.TryLock() {
			w.Header().Set("Retry-After", "1")
			http.Error(w, "应急登录验证繁忙，请稍后重试", http.StatusTooManyRequests)
			return
		}
		digest := emergencyDigest(input.Password, password.salt)
		password.verify.Unlock()
		if subtle.ConstantTimeCompare(digest, password.digest) != 1 {
			http.Error(w, "应急密码错误", http.StatusUnauthorized)
			return
		}
		operator := administrator{ID: emergencyAccountID, Username: "应急管理员"}
		// Replace the local session without calling PhotoLib to revoke an older pairing.
		if !a.saveSession(w, r, adminSession{administrator: operator, privileged: true}, sessionLife) {
			http.Error(w, "会话较多，请稍后登录", http.StatusServiceUnavailable)
			return
		}
		logger.Info("emergency administrator logged in", "user_id", operator.ID)
		w.WriteHeader(http.StatusNoContent)
	}
}
